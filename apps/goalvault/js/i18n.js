const listeners = new Set();

function readStored() {
  try {
    const v = globalThis.localStorage?.getItem(KEY);
    return v && DICT[v] ? v : null;
  } catch {
    return null;
  }
}

let lang = readStored() ?? 'vi';

export const getLang = () => lang;

export function setLang(next) {
  if (!DICT[next] || next === lang) return;
  lang = next;
  try { globalThis.localStorage?.setItem(KEY, next); } catch { /* storage unavailable */ }
  if (globalThis.document) document.documentElement.lang = next;
  listeners.forEach((cb) => cb(next));
}

export function onLangChange(cb) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

export function t(key, params = {}) {
  const s = DICT[lang][key] ?? DICT.vi[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}
